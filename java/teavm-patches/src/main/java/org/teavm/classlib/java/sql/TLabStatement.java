package org.teavm.classlib.java.sql;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import lab.sql.Result;
import lab.sql.Session;
import lab.sql.SqlError;

/** Statement and PreparedStatement of the embedded database (messages of MySQL Connector/J). */
final class TLabStatement implements TPreparedStatement {
    private final TLabConnection connection;
    private final String sql;                 // null for a plain Statement
    private final boolean wantKeys;
    private Object[] params;
    private final List<Object[]> batchParams = new ArrayList<>();
    private final List<String> batchSql = new ArrayList<>();
    private boolean closed;
    private TLabResultSet current;
    private long updateCount = -1;
    private Result lastResult;
    private int maxRows;
    private int queryTimeout;
    private int fetchSize;

    TLabStatement(TLabConnection connection, String sql, boolean wantKeys) throws TSQLException {
        this.connection = connection;
        this.sql = sql;
        this.wantKeys = wantKeys;
        if (sql != null) {
            try {
                params = new Object[Session.parameterCount(sql)];
            } catch (SqlError e) {
                throw TLabSqlErrors.of(e);
            }
            Arrays.fill(params, Session.UNSET);
        }
    }

    private void check() throws TSQLException {
        if (closed) {
            throw new TSQLException("No operations allowed after statement closed.", "S1009");
        }
        connection.check();
    }

    private Result run(String text, Object[] values) throws TSQLException {
        check();
        if (current != null) {
            current.close();
            current = null;
        }
        if (text == null || text.trim().isEmpty()) {
            throw new TSQLException("Can not issue empty query.", "S1009");
        }
        try {
            Result r = connection.session.execute(text, values == null ? new Object[0] : values);
            lastResult = r;
            if (r.query) {
                if (maxRows > 0 && r.rows.size() > maxRows) {
                    r.rows = new ArrayList<>(r.rows.subList(0, maxRows));
                }
                current = new TLabResultSet(this, r);
                updateCount = -1;
            } else {
                updateCount = r.updateCount;
            }
            return r;
        } catch (SqlError e) {
            throw TLabSqlErrors.of(e);
        }
    }

    private static boolean isSelect(String text) {
        String t = text.trim();
        while (t.startsWith("(")) {
            t = t.substring(1).trim();
        }
        String word = t.length() >= 6 ? t.substring(0, 6).toUpperCase() : t.toUpperCase();
        return word.startsWith("SELECT") || word.startsWith("SHOW") || word.startsWith("DESC");
    }

    private void needPrepared() throws TSQLException {
        if (sql == null) {
            throw new TSQLException("This method cannot be called on a Statement; use a PreparedStatement.", "S1009");
        }
    }

    private void notOnPrepared() throws TSQLException {
        if (sql != null) {
            throw new TSQLException("Can not call this method with a SQL string on a PreparedStatement.", "S1009");
        }
    }

    // ------------------------------------------------------------ Statement
    @Override
    public TResultSet executeQuery(String text) throws TSQLException {
        notOnPrepared();
        return query(text, null);
    }

    private static boolean isDataManipulation(String text) {
        String t = text.trim().toUpperCase();
        for (String w : new String[] {"INSERT", "UPDATE", "DELETE", "DROP", "CREATE", "ALTER", "TRUNCATE", "RENAME",
            "REPLACE", "GRANT", "REVOKE", "LOAD"}) {
            if (t.startsWith(w) && (t.length() == w.length() || !Character.isLetterOrDigit(t.charAt(w.length())))) {
                return true;
            }
        }
        return false;
    }

    private TResultSet query(String text, Object[] values) throws TSQLException {
        if (text != null && isDataManipulation(text)) {     // checked by Connector/J before sending
            throw new TSQLException("Can not issue data manipulation statements with executeQuery().", "S1009");
        }
        Result r = run(text, values);
        if (!r.query) {
            throw new TSQLException("Statement.executeQuery() cannot issue statements that do not produce result sets.", "S1009");
        }
        return current;
    }

    @Override
    public int executeUpdate(String text) throws TSQLException {
        notOnPrepared();
        return (int) update(text, null);
    }

    @Override
    public int executeUpdate(String text, int autoGeneratedKeys) throws TSQLException {
        return executeUpdate(text);
    }

    @Override
    public long executeLargeUpdate(String text) throws TSQLException {
        notOnPrepared();
        return update(text, null);
    }

    private long update(String text, Object[] values) throws TSQLException {
        if (text != null && isSelect(text)) {
            throw new TSQLException("Can not issue SELECT via executeUpdate() or executeLargeUpdate().", "S1009");
        }
        Result r = run(text, values);
        return Math.max(0, r.updateCount);
    }

    @Override
    public boolean execute(String text) throws TSQLException {
        notOnPrepared();
        return run(text, null).query;
    }

    @Override
    public boolean execute(String text, int autoGeneratedKeys) throws TSQLException {
        return execute(text);
    }

    @Override
    public TResultSet getResultSet() throws TSQLException {
        check();
        return current;
    }

    @Override
    public int getUpdateCount() throws TSQLException {
        check();
        return (int) updateCount;
    }

    @Override
    public boolean getMoreResults() throws TSQLException {
        check();
        if (current != null) {
            current.close();
            current = null;
        }
        updateCount = -1;
        return false;
    }

    @Override
    public TResultSet getGeneratedKeys() throws TSQLException {
        check();
        Result keys = new Result();
        keys.query = true;
        keys.labels = new String[] {"GENERATED_KEY"};
        keys.names = keys.labels;
        keys.sqlTypes = new int[] {-5};
        keys.typeNames = new String[] {"BIGINT UNSIGNED"};
        if (lastResult != null) {
            for (Long k : lastResult.generatedKeys) {
                keys.rows.add(new Object[] {k});
            }
        }
        return new TLabResultSet(this, keys);
    }

    @Override
    public void addBatch(String text) throws TSQLException {
        check();
        notOnPrepared();
        batchSql.add(text);
    }

    @Override
    public void clearBatch() throws TSQLException {
        check();
        batchSql.clear();
        batchParams.clear();
    }

    @Override
    public int[] executeBatch() throws TSQLException {
        check();
        int[] counts;
        if (sql == null) {
            counts = new int[batchSql.size()];
            for (int i = 0; i < counts.length; i++) {
                counts[i] = (int) update(batchSql.get(i), null);
            }
        } else {
            counts = new int[batchParams.size()];
            for (int i = 0; i < counts.length; i++) {
                counts[i] = (int) update(sql, batchParams.get(i));
            }
        }
        clearBatch();
        return counts;
    }

    @Override
    public void setMaxRows(int max) throws TSQLException {
        check();
        maxRows = max;
    }

    @Override
    public int getMaxRows() throws TSQLException {
        check();
        return maxRows;
    }

    @Override
    public void setQueryTimeout(int seconds) throws TSQLException {
        check();
        queryTimeout = seconds;
    }

    @Override
    public int getQueryTimeout() throws TSQLException {
        check();
        return queryTimeout;
    }

    @Override
    public void setFetchSize(int rows) throws TSQLException {
        check();
        fetchSize = rows;
    }

    @Override
    public int getFetchSize() throws TSQLException {
        check();
        return fetchSize;
    }

    @Override
    public TConnection getConnection() throws TSQLException {
        check();
        return connection;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public void close() {
        if (current != null) {
            current.close();
        }
        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    // ------------------------------------------------------------ PreparedStatement
    @Override
    public TResultSet executeQuery() throws TSQLException {
        needPrepared();
        return query(sql, params);
    }

    @Override
    public int executeUpdate() throws TSQLException {
        needPrepared();
        return (int) update(sql, params);
    }

    @Override
    public long executeLargeUpdate() throws TSQLException {
        needPrepared();
        return update(sql, params);
    }

    @Override
    public boolean execute() throws TSQLException {
        needPrepared();
        return run(sql, params).query;
    }

    @Override
    public void addBatch() throws TSQLException {
        check();
        needPrepared();
        for (int i = 0; i < params.length; i++) {
            if (params[i] == Session.UNSET) {
                throw new TSQLException("No value specified for parameter " + (i + 1), "07001");
            }
        }
        batchParams.add(params.clone());
    }

    @Override
    public void clearParameters() throws TSQLException {
        check();
        needPrepared();
        Arrays.fill(params, Session.UNSET);
    }

    private void set(int index, Object value) throws TSQLException {
        check();
        needPrepared();
        if (index < 1 || index > params.length) {
            throw new TSQLException("Parameter index out of range (" + index + " > number of parameters, which is "
                    + params.length + ").", "S1009");
        }
        params[index - 1] = value;
    }

    @Override
    public void setNull(int parameterIndex, int sqlType) throws TSQLException {
        set(parameterIndex, null);
    }

    @Override
    public void setBoolean(int parameterIndex, boolean x) throws TSQLException {
        set(parameterIndex, x ? 1L : 0L);
    }

    @Override
    public void setByte(int parameterIndex, byte x) throws TSQLException {
        set(parameterIndex, (long) x);
    }

    @Override
    public void setShort(int parameterIndex, short x) throws TSQLException {
        set(parameterIndex, (long) x);
    }

    @Override
    public void setInt(int parameterIndex, int x) throws TSQLException {
        set(parameterIndex, (long) x);
    }

    @Override
    public void setLong(int parameterIndex, long x) throws TSQLException {
        set(parameterIndex, x);
    }

    @Override
    public void setFloat(int parameterIndex, float x) throws TSQLException {
        set(parameterIndex, Double.parseDouble(Float.toString(x)));
    }

    @Override
    public void setDouble(int parameterIndex, double x) throws TSQLException {
        set(parameterIndex, x);
    }

    @Override
    public void setBigDecimal(int parameterIndex, java.math.BigDecimal x) throws TSQLException {
        set(parameterIndex, x);
    }

    @Override
    public void setString(int parameterIndex, String x) throws TSQLException {
        set(parameterIndex, x);
    }

    @Override
    public void setObject(int parameterIndex, Object x) throws TSQLException {
        if (x == null || x instanceof String || x instanceof Long || x instanceof Double) {
            set(parameterIndex, x);
        } else if (x instanceof Integer || x instanceof Short || x instanceof Byte) {
            set(parameterIndex, ((Number) x).longValue());
        } else if (x instanceof Float) {
            setFloat(parameterIndex, (Float) x);
        } else if (x instanceof java.math.BigDecimal) {
            set(parameterIndex, x);
        } else if (x instanceof Number) {
            set(parameterIndex, ((Number) x).doubleValue());
        } else if (x instanceof Boolean) {
            setBoolean(parameterIndex, (Boolean) x);
        } else if (x instanceof Character) {
            set(parameterIndex, x.toString());
        } else {
            set(parameterIndex, x.toString());
        }
    }

    @Override
    public void setObject(int parameterIndex, Object x, int targetSqlType) throws TSQLException {
        setObject(parameterIndex, x);
    }

    @Override
    public TResultSetMetaData getMetaData() throws TSQLException {
        check();
        return current == null ? null : current.getMetaData();
    }

    boolean wantsKeys() {
        return wantKeys;
    }
}
