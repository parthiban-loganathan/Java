package org.teavm.classlib.java.sql;

import lab.sql.Session;
import lab.sql.SqlError;
import lab.web.BrowserSql;

/** A connection to the embedded database. */
final class TLabConnection implements TConnection {
    final Session session;
    private boolean closed;
    private boolean readOnly;
    private int isolation = TRANSACTION_REPEATABLE_READ;

    private TLabConnection(Session session) {
        this.session = session;
    }

    /** jdbc:subprotocol://host:port/database?options, jdbc:subprotocol:database, ... */
    static TLabConnection open(String url) throws TSQLException {
        if (url == null) {
            throw new TSQLException("The url cannot be null", "08001");
        }
        if (!url.startsWith("jdbc:")) {
            throw new TSQLException("No suitable driver found for " + url, "08001");
        }
        String rest = url.substring(5);
        int q = rest.indexOf('?');
        if (q >= 0) {
            rest = rest.substring(0, q);
        }
        int colon = rest.indexOf(':');
        String path = colon >= 0 ? rest.substring(colon + 1) : rest;
        String database;
        if (path.startsWith("//")) {
            int slash = path.indexOf('/', 2);
            database = slash >= 0 ? path.substring(slash + 1) : "";
        } else {
            database = path;
            int semi = database.indexOf(';');
            if (semi >= 0) {
                database = database.substring(0, semi);
            }
            int lastSlash = Math.max(database.lastIndexOf('/'), database.lastIndexOf(':'));
            database = database.substring(lastSlash + 1);
            if (database.endsWith(".db")) {
                database = database.substring(0, database.length() - 3);
            }
        }
        int semi = database.indexOf(';');
        if (semi >= 0) {
            database = database.substring(0, semi);
        }
        try {
            Session.initialise(BrowserSql.setupScript());
            return new TLabConnection(new Session(database.isEmpty() ? null : database));
        } catch (SqlError e) {
            throw TLabSqlErrors.of(e);
        }
    }

    void check() throws TSQLException {
        if (closed) {
            throw new TSQLException("No operations allowed after connection closed.", "08003");
        }
    }

    @Override
    public TStatement createStatement() throws TSQLException {
        check();
        return new TLabStatement(this, null, false);
    }

    @Override
    public TStatement createStatement(int resultSetType, int resultSetConcurrency) throws TSQLException {
        return createStatement();
    }

    @Override
    public TPreparedStatement prepareStatement(String sql) throws TSQLException {
        check();
        return new TLabStatement(this, sql, false);
    }

    @Override
    public TPreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws TSQLException {
        check();
        return new TLabStatement(this, sql, autoGeneratedKeys == TStatement.RETURN_GENERATED_KEYS);
    }

    @Override
    public TPreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws TSQLException {
        return prepareStatement(sql);
    }

    @Override
    public TPreparedStatement prepareStatement(String sql, String[] columnNames) throws TSQLException {
        check();
        return new TLabStatement(this, sql, true);
    }

    @Override
    public String nativeSQL(String sql) {
        return sql;
    }

    @Override
    public void setAutoCommit(boolean autoCommit) throws TSQLException {
        check();
        session.setAutoCommit(autoCommit);
    }

    @Override
    public boolean getAutoCommit() throws TSQLException {
        check();
        return session.getAutoCommit();
    }

    @Override
    public void commit() throws TSQLException {
        check();
        if (session.getAutoCommit()) {
            throw new TSQLException("Can't call commit when autocommit=true", "08003");
        }
        session.commit();
    }

    @Override
    public void rollback() throws TSQLException {
        check();
        if (session.getAutoCommit()) {
            throw new TSQLException("Can't call rollback when autocommit=true", "08003");
        }
        session.rollback();
    }

    @Override
    public void close() {
        if (!closed && !session.getAutoCommit()) {
            session.rollback();
        }
        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public boolean isValid(int timeout) {
        return !closed;
    }

    @Override
    public void setReadOnly(boolean readOnly) throws TSQLException {
        check();
        this.readOnly = readOnly;
    }

    @Override
    public boolean isReadOnly() throws TSQLException {
        check();
        return readOnly;
    }

    @Override
    public void setCatalog(String catalog) throws TSQLException {
        check();
        try {
            session.setSchema(catalog);
        } catch (SqlError e) {
            throw TLabSqlErrors.of(e);
        }
    }

    @Override
    public String getCatalog() throws TSQLException {
        check();
        return session.getSchema();
    }

    @Override
    public void setSchema(String schema) throws TSQLException {
        setCatalog(schema);
    }

    @Override
    public String getSchema() throws TSQLException {
        return null;
    }

    @Override
    public void setTransactionIsolation(int level) throws TSQLException {
        check();
        isolation = level;
    }

    @Override
    public int getTransactionIsolation() throws TSQLException {
        check();
        return isolation;
    }

    @Override
    public void clearWarnings() {
    }
}
